<?php

declare(strict_types=1);

use Lib\Core\Database;
use Lib\Support\Hash;

// This file ensures the minimum required tables exist on first boot:
// settings, visits, users and system_settings. Any other table must
// be created by the system programmer for each project.
//
// El SQL se genera segun el driver activo (mysql | pgsql), de modo que
// el sistema funciona igual con MySQL/MariaDB o PostgreSQL.
//
// Runs only once per connection+database: the storage/.installed marker
// stores "connection:database". Delete that file to re-run the setup.

$connection = (string) config('database.default');
$database = (string) config("database.connections.{$connection}.database");
$marker = BASE_PATH . '/storage/.installed';
$installation = $connection . ':' . $database;

if (is_file($marker) && trim((string) file_get_contents($marker)) === $installation) {
    return;
}

try {
    $db = Database::connection();
    $isPgsql = Database::isPgsql();

    $tableExists = static function (string $table) use ($db, $isPgsql): bool {
        if ($isPgsql) {
            $stmt = $db->prepare(
                'SELECT 1 FROM information_schema.tables
                 WHERE table_schema = current_schema() AND table_name = :table'
            );
            $stmt->execute(['table' => $table]);

            return $stmt->fetchColumn() !== false;
        }

        return $db->query("SHOW TABLES LIKE '{$table}'")->fetchColumn() !== false;
    };

    if (!$tableExists('settings')) {
        $db->exec($isPgsql
            ? "CREATE TABLE IF NOT EXISTS settings (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    site_name VARCHAR(255) DEFAULT 'Sistema CMS',
                    timezone VARCHAR(100) DEFAULT 'America/La_Paz',
                    maintenance_mode SMALLINT DEFAULT 0,
                    created_at TIMESTAMP NULL,
                    updated_at TIMESTAMP NULL
                )"
            : "CREATE TABLE IF NOT EXISTS settings (
                    id BIGINT PRIMARY KEY AUTO_INCREMENT,
                    site_name VARCHAR(255) DEFAULT 'Sistema CMS',
                    timezone VARCHAR(100) DEFAULT 'America/La_Paz',
                    maintenance_mode BOOLEAN DEFAULT 0,
                    created_at TIMESTAMP NULL,
                    updated_at TIMESTAMP NULL
                )");
    }

    if (!$tableExists('visits')) {
        $db->exec($isPgsql
            ? "CREATE TABLE IF NOT EXISTS visits (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ip_address VARCHAR(45),
                    country VARCHAR(100),
                    city VARCHAR(100),
                    browser VARCHAR(100),
                    operating_system VARCHAR(100),
                    device_type VARCHAR(50),
                    language VARCHAR(20),
                    page_url TEXT,
                    referer_url TEXT,
                    user_agent TEXT,
                    visited_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )"
            : "CREATE TABLE IF NOT EXISTS visits (
                    id BIGINT PRIMARY KEY AUTO_INCREMENT,
                    ip_address VARCHAR(45),
                    country VARCHAR(100),
                    city VARCHAR(100),
                    browser VARCHAR(100),
                    operating_system VARCHAR(100),
                    device_type VARCHAR(50),
                    language VARCHAR(20),
                    page_url TEXT,
                    referer_url TEXT,
                    user_agent TEXT,
                    visited_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )");
    }

    if (!$tableExists('users')) {
        $db->exec($isPgsql
            ? "CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100),
                    email VARCHAR(150) UNIQUE,
                    password VARCHAR(255),
                    status SMALLINT DEFAULT 1,
                    created_at TIMESTAMP NULL,
                    updated_at TIMESTAMP NULL
                )"
            : "CREATE TABLE IF NOT EXISTS users (
                    id BIGINT PRIMARY KEY AUTO_INCREMENT,
                    name VARCHAR(100),
                    email VARCHAR(150) UNIQUE,
                    password VARCHAR(255),
                    status TINYINT(1) DEFAULT 1,
                    created_at TIMESTAMP NULL,
                    updated_at TIMESTAMP NULL
                )");
    }

    if ($tableExists('users')) {
        $hasRoleColumn = $isPgsql
            ? $db->query("SELECT 1 FROM information_schema.columns
                          WHERE table_schema = current_schema() AND table_name = 'users' AND column_name = 'role'")->fetchColumn()
            : $db->query("SHOW COLUMNS FROM users LIKE 'role'")->fetchColumn();

        if ($hasRoleColumn !== false) {
            $db->exec('ALTER TABLE users DROP COLUMN role');
        }
    }

    if (!$tableExists('system_settings')) {
        $keyColumn = Database::quoteIdentifier('key');
        $valueColumn = Database::quoteIdentifier('value');

        $db->exec("
            CREATE TABLE IF NOT EXISTS system_settings (
                {$keyColumn} VARCHAR(190) PRIMARY KEY,
                {$valueColumn} TEXT NULL,
                updated_at TIMESTAMP NULL
            )
        ");
    }

    $count = $db->query('SELECT COUNT(*) FROM settings')->fetchColumn();

    if ($count == 0) {
        $db->exec("
            INSERT INTO settings (site_name, timezone, maintenance_mode, created_at, updated_at)
            VALUES ('Sistema CMS', 'America/La_Paz', 0, NOW(), NOW())
        ");
    }

    $userCount = $db->query('SELECT COUNT(*) FROM users')->fetchColumn();

    if ($userCount == 0) {
        $stmt = $db->prepare("
            INSERT INTO users (name, email, password, status, created_at, updated_at)
            VALUES (:name, :email, :password, 1, NOW(), NOW())
        ");

        $stmt->execute([
            'name' => 'Administrador',
            'email' => 'admin',
            'password' => Hash::make('admin123'),
        ]);
    }

    if (!is_dir(dirname($marker))) {
        mkdir(dirname($marker), 0777, true);
    }

    file_put_contents($marker, $installation);
} catch (Throwable $e) {
    error_log('Setup error: ' . $e->getMessage());
}
